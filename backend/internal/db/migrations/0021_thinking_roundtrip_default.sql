-- 显式挂载优先：渠道协议一旦挂载 thinking-roundtrip，以挂载参数为准（enabled 缺省 false），
-- 全局默认只作用于「未挂载」的渠道。存量「挂载但未开 enabled」的渠道行为不变。
--
-- 注意 ON CONFLICT DO NOTHING：若运维已写入该键（如显式关闭），本迁移不改动其值。
